export const FALLBACK_BUNDLES: Record<Locale, Record<string, string>> = {
  ar: AR,
  fr: FR,
  en: EN,
};

// Backwards-compatible alias (Arabic is the default locale).
export const FALLBACK_MESSAGES = AR;

export function fallbackFor(locale: Locale): Record<string, string> {
  return FALLBACK_BUNDLES[locale] ?? AR;
}

// Last-resort humaniser so an unknown key still renders something legible
// instead of an empty string. "trip.status.IN_PROGRESS" -> "In Progress".
export function humanizeKey(key: string): string {
  const last = key.split(".").pop() ?? key;
  if (/^[A-Z0-9_]+$/.test(last)) {
    return last
      .split("_")
      .filter(Boolean)
      .map((word) => word.charAt(0) + word.slice(1).toLowerCase())
      .join(" ");
  }
  const spaced = last.replace(/([a-z0-9])([A-Z])/g, "$1 $2");
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}
